"""Writes lib/src/glyphs/arabic_tables.g.dart from the Unicode database.

    python3 tool/gen_arabic_tables.py ArabicShaping.txt

ArabicShaping.txt comes from https://www.unicode.org/Public/UCD/latest/ucd/.
Presentation forms come from Python's own copy of UnicodeData, by their
<isolated>, <final>, <initial> and <medial> decompositions.
"""

import sys
import unicodedata

FORMS = ['<isolated>', '<final>', '<initial>', '<medial>']
TYPES = 'UTDRLC'
BLOCKS = [(0x0600, 0x08FF), (0xFB50, 0xFDFF), (0xFE70, 0xFEFF)]


def in_blocks(c):
    return any(a <= c <= b for a, b in BLOCKS)


types = {}
for line in open(sys.argv[1], encoding='utf-8'):
    line = line.split('#')[0].strip()
    if not line:
        continue
    code, _, kind, _ = [f.strip() for f in line.split(';')]
    c = int(code, 16)
    if in_blocks(c):
        types[c] = kind
for a, b in BLOCKS:
    for c in range(a, b + 1):
        if c not in types and unicodedata.category(chr(c)) in ('Mn', 'Me', 'Cf'):
            types[c] = 'T'

forms = {}
ligatures = {}
for a, b in BLOCKS[1:]:
    for c in range(a, b + 1):
        parts = unicodedata.decomposition(chr(c)).split()
        if not parts or parts[0] not in FORMS:
            continue
        form = FORMS.index(parts[0])
        bases = [int(p, 16) for p in parts[1:]]
        if len(bases) == 1:
            forms.setdefault(bases[0], [0, 0, 0, 0])[form] = c
        elif len(bases) == 2 and bases[0] == 0x0644 and 'ALEF' in unicodedata.name(chr(bases[1])):
            ligatures.setdefault(bases[1], [0, 0, 0, 0])[form] = c

out = ['// Generated by tool/gen_arabic_tables.py from Unicode '
       + unicodedata.unidata_version + ' and ArabicShaping.txt. Do not edit.',
       '',
       "part of 'arabic_forms.dart';",
       '',
       '/// Joining types that are not U, by code point: T, D, R, L or C.',
       'const Map<int, int> _joiningTypes = {']
for c in sorted(types):
    if types[c] != 'U':
        out.append(f'  0x{c:04X}: {TYPES.index(types[c])},')
out += ['};', '',
        '/// Presentation forms by letter: isolated, final, initial, medial;',
        '/// 0 where Unicode has none.',
        'const Map<int, List<int>> _presentation = {']
for c in sorted(forms):
    out.append(f'  0x{c:04X}: [' + ', '.join(f'0x{f:04X}' for f in forms[c]) + '],')
out += ['};', '',
        '/// Lam followed by an alef as one ligature, in the same forms.',
        'const Map<int, List<int>> _lamLigatures = {']
for c in sorted(ligatures):
    out.append(f'  0x{c:04X}: [' + ', '.join(f'0x{f:04X}' for f in ligatures[c]) + '],')
out.append('};')
open('lib/src/glyphs/arabic_tables.g.dart', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(len(types), 'joining types,', len(forms), 'letters with forms,', len(ligatures), 'lam ligatures')
