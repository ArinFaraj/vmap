bool _isCursive(int codePoint) {
  var lo = 0, hi = _cursive.length - 1;
  while (lo <= hi) {
    final mid = (lo + hi) >> 1;
    final (start, end) = _cursive[mid];
    if (codePoint < start) {
      hi = mid - 1;
    } else if (codePoint > end) {
      lo = mid + 1;
    } else {
      return true;
    }
  }
  return false;
}

/// [spacing], or none when [text] holds a letter of a cursive script, as
/// MapLibre turns off text-letter-spacing for a whole label then.
double letterSpacingFor(String text, double spacing) {
  if (spacing == 0) return 0;
  for (final r in text.runes) {
    if (_isCursive(r)) return 0;
  }
  return spacing;
}
